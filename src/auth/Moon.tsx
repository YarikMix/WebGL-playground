import type { CSSProperties, ReactNode } from 'react';

/* Рельеф луны: кратеры — настоящие элементы, а не слои градиента.

   У впадины освещена дальняя от света стенка и затенена ближняя, то есть нужны две дуги по
   краю круга. Радиальный градиент так не умеет: он симметричен относительно своего центра.
   Первая версия собирала кратер из двух смещённых градиентов — на экране вышли размытые
   пятна, похожие на мыльные пузыри, а не на рельеф. Пара inset-теней на круглом элементе
   даёт ровно эти дуги.

   Свет в кадре падает сверху слева (базовый градиент луны `circle at 34% 28%`), поэтому
   тень внутри лежит на верхней левой стенке, а блик — на нижней правой. Внешних теней у
   кратера нет намеренно: пара «светлое сверху-слева, тёмное снизу-справа» снаружи — это
   подпись приподнятого предмета, и она перебивает внутреннюю лепку. С ней всё поле
   выглядело пузырчатой плёнкой (проверено на скриншоте), без неё — впадинами.

   Четвёртое число — глубина: множитель прозрачности обеих внутренних теней. Без разброса
   поле читается штампом; мелкие кратеры должны быть едва заметны.

   Координаты и диаметр в px и подогнаны под --moon: 420px (styles.css) — это прежняя
   раскладка для круга 600px, умноженная на 0,7, когда луна стала целым кругом внутри своей
   половины карточки. Крупные кратеры по-прежнему разведены за пределы полосы, по которой
   идёт надпись, чтобы текст лежал на ровной поверхности. */
