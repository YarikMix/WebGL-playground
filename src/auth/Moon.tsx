/* Половина с приглашением. Обёртка вокруг содержимого, а не отдельная разметка в AuthCard:
   рельеф — это оформление поверхности, а не содержание карточки, и держать тридцать пустых
   узлов посреди формы незачем. */
export default function Moon({ children }: { children: ReactNode }) {
  return (
    <div className="auth-invite">
      {/* aria-hidden: рельеф читать нечего. fontSize = диаметру — все размеры теней в CSS
          заданы в em, поэтому геометрия кратера масштабируется вместе с ним сама. */}
      <div className="moon-relief" aria-hidden="true">
        {CRATERS.map(([cx, cy, d, depth], i) => (
          <span key={i} className="moon-crater"
            style={{ left: cx - d / 2, top: cy - d / 2, width: d, height: d, fontSize: d, '--k': depth } as CSSProperties} />
        ))}
      </div>
      {children}
    </div>
  );
}
