/* Константы подстройки сцены. Отдельный модуль, потому что ими пользуются и `src/sky/*`,
   и экраны: класть их в types.ts значило бы смешать значения с типами (при verbatimModuleSyntax
   это ловушка), а в src/auth/ — заставить слой сцены зависеть от слоя форм. */
import type { SunDirection } from './types';

/** Солнце главной: стоит за планетой, поэтому освещён узкий серп у кромки.

    Ruling 9 (правка спеки после провала §3.2): карточка входа стоит НА кромке, поэтому терминатор —
    деталь поверхности планеты — физически не может пройти через её середину: карточка почти
    целиком на фоне неба, а не диска. Нужный эффект уже был в сцене — направленный ореол
    атмосферы (`sunSide` в Planet.tsx и Backdrop.tsx), который светится только с солнечной
    стороны. Значит за половину карточки заходит не граница дня/ночи, а освещённая кромка
    с ореолом.

    Солнце входа — та же композиция, что и у главной (коммит 075c6cb, shots/task3-fix1.png):
    дуга кромки идёт через низ карточки по центру. От этой базы солнце поворачивается вбок
    в плоскости экрана на угол SWEEP_ANGLE/2 в каждую сторону (см. spin в App.tsx и поворот
    uSun.xy в Planet.tsx/Backdrop.tsx) — так ореол смещается под одну половину карточки,
    а не гаснет: в покое входа на -SWEEP_ANGLE/2 (ореол за правой половиной, где приглашение),
    в покое регистрации на +SWEEP_ANGLE/2 (ореол уезжает за левую половину, куда переехало
    приглашение). Солнце у обоих экранов одно и то же — вход не заводит собственного. */
export const SUN_ORBIT: SunDirection = [0, 0.38, -0.925];

/* Одна длительность на оба конца: CSS-переход формы и доворот солнца в useFrame.
   Идеальной синхронности кадр-в-кадр не будет — часы разные, — но глаз ловит только
   грубое рассогласование, поэтому важно, чтобы число было одно. */
export const SWEEP_MS = 700;

/* Свет идёт за той же константой, что и форма. Попытка дать ему собственное, более длинное
   время успокоения (1400 мс) сделала переход рассинхронным: форма уже встала, а планета ещё
   ехала, и связь между ними перестала читаться. Подсветка стороны — это индикатор состояния
   формы, значит она обязана двигаться вместе с ней. */
/* Полный угол поворота солнца вокруг Z (в плоскости экрана) между покоем входа и покоем
   регистрации — карточка получает ±половину. Достаточно ровно того, чтобы яркое место кромки
   переехало под другую половину карточки: половина — это 450px при видимой ширине кромки
   в тысячи пикселей. 1.4 (80°) меняло освещение кромки целиком и читалось как скачок фона;
   0.5 не читалось вовсе. */
export const SWEEP_ANGLE = 0.9;
